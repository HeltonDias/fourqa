CREATE TABLE workbook_meta (
  key text PRIMARY KEY,
  value text
);

CREATE TABLE planejamento_linhas (
  row_num integer PRIMARY KEY,
  qa text,
  prioridades text,
  frente text,
  processo text,
  data_inicio text,
  data_fim text,
  replanejamento double precision,
  qtd_cts_plan double precision,
  cts_plan_dia double precision,
  cts_cancelados double precision
);

CREATE TABLE execucoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_key text,
  plan_id integer,
  plan_name text,
  frente text,
  atalho text,
  processo text,
  suite_id integer,
  suite_name text,
  parent_suite_id integer,
  suite_depth integer,
  suite_path text,
  dimensions_json text,
  test_point_id integer,
  test_case_id integer,
  test_case_title text,
  responsabilidade text,
  test_case_state text,
  test_point_state text,
  outcome text,
  date_completed text,
  run_by text,
  last_updated_date text,
  last_test_run_id integer,
  last_result_id integer,
  test_case_link text,
  test_case_tags text
);

CREATE INDEX idx_exec_plan ON execucoes (plan_key);
CREATE INDEX idx_exec_suite ON execucoes (suite_name);
CREATE INDEX idx_exec_point ON execucoes (plan_key, test_point_id);

CREATE TABLE falhas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_key text,
  responsavel text,
  ambiente text,
  categoria text,
  bug_id integer,
  impacto double precision,
  frente text,
  titulo text,
  status text,
  criacao text,
  fechamento text,
  links text,
  tags text
);

CREATE INDEX idx_falhas_plan ON falhas (plan_key);
CREATE INDEX idx_falhas_frente ON falhas (frente);

CREATE TABLE planning (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_key text NOT NULL UNIQUE,
  created_at text NOT NULL
);

CREATE TABLE planning_revision (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planning_id integer NOT NULL REFERENCES planning (id),
  version integer NOT NULL,
  created_at text NOT NULL,
  reason text NOT NULL,
  baseline_origin text NOT NULL,
  scope_snapshot smallint NOT NULL DEFAULT 0,
  UNIQUE (planning_id, version)
);

CREATE INDEX idx_plan_rev ON planning_revision (planning_id, version);

CREATE TABLE planning_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  revision_id integer NOT NULL REFERENCES planning_revision (id),
  suite_id integer,
  suite_name text,
  planned_start text,
  planned_end text,
  baseline_quantity double precision
);

CREATE INDEX idx_plan_item_rev ON planning_item (revision_id);

CREATE TABLE planning_scope_item (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  revision_id integer NOT NULL REFERENCES planning_revision (id),
  plan_id integer,
  suite_id integer,
  test_point_id integer,
  test_case_id integer,
  label text
);

CREATE INDEX idx_plan_scope_rev ON planning_scope_item (revision_id, test_point_id);

CREATE TABLE planning_allocation (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id integer NOT NULL REFERENCES planning_item (id),
  alloc_date text NOT NULL,
  planned_quantity double precision NOT NULL,
  UNIQUE (item_id, alloc_date)
);

CREATE INDEX idx_plan_alloc_item ON planning_allocation (item_id, alloc_date);
